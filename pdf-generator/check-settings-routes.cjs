const puppeteer = require('puppeteer');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const browser = await puppeteer.launch({executablePath: path.resolve(__dirname, 'chrome/mac_arm-153.0.8010.36/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing'), headless: true});
  try {
    const page = await browser.newPage();
    const errors = [];
    page.on('pageerror', error => {errors.push(error.message); console.error('Browser error:', error.stack);});
    await page.setViewport({width: 1440, height: 1000, deviceScaleFactor: 1});
    await page.emulateMediaFeatures([{name: 'prefers-color-scheme', value: 'light'}]);
    const click = async (selector, text) => {
      const button = await page.evaluateHandle(({selector, text}) => Array.from(document.querySelectorAll(selector)).find(e => e.textContent.trim().startsWith(text)), {selector, text});
      assert(button.asElement(), 'Missing control: ' + text);
      await button.asElement().click(); await button.dispose();
    };
    const screenshot = async name => {await new Promise(resolve => setTimeout(resolve, 250)); return page.screenshot({path: path.resolve(__dirname, '../artifacts/' + name + '.png'), fullPage: true});};
    const noOverflow = async () => assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Horizontal overflow: ' + page.url());
    await page.goto('http://127.0.0.1:5173/settings', {waitUntil: 'networkidle2'});
    await page.waitForFunction(() => document.documentElement.dataset.theme === 'light');
    await page.evaluate(() => document.fonts.ready);
    await screenshot('settings-light-desktop');
    await click('[aria-label="Colour theme"] button', 'Dark');
    await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
    assert.equal(await page.evaluate(() => getComputedStyle(document.body).backgroundColor), 'rgb(17, 19, 27)');
    await click('[aria-label="Navigation position"] button', 'At the bottom');
    assert.equal(await page.$eval('.desktop-nav', e => getComputedStyle(e).display), 'none');
    await page.reload({waitUntil: 'networkidle2'});
    assert.equal(await page.evaluate(() => document.documentElement.dataset.theme), 'dark');
    assert(await page.$('.app.nav-bottom'));
    await screenshot('settings-dark-desktop');
    await click('[aria-label="Navigation position"] button', 'At the top');
    assert.equal(await page.$eval('.bottom-nav', e => getComputedStyle(e).display), 'none');
    await click('[aria-label="Navigation position"] button', 'Top & bottom');
    await click('[aria-label="Colour theme"] button', 'System');
    await page.waitForFunction(() => document.documentElement.dataset.theme === 'light');
    await page.emulateMediaFeatures([{name: 'prefers-color-scheme', value: 'dark'}]);
    await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
    await page.setViewport({width: 390, height: 844, deviceScaleFactor: 1});
    await screenshot('settings-dark-mobile'); await noOverflow();
    await click('[aria-label="Navigation position"] button', 'At the top');
    assert.equal(await page.$eval('.bottom-nav', e => getComputedStyle(e).display), 'flex');
    await click('[aria-label="Navigation position"] button', 'Top & bottom');
    await page.click('.site-header .logo');
    await page.waitForSelector('.hero');
    await screenshot('home-stitch-dark-mobile'); await noOverflow();
    await page.click('[aria-label="Switch to light mode"]');
    await screenshot('home-stitch-light-mobile');
    await page.setViewport({width: 1440, height: 1000, deviceScaleFactor: 1});
    await click('.bottom-nav button', 'Trips');
    await page.waitForSelector('.route-metrics, .route-error', {timeout: 25000});
    console.log('Live route:', await page.$eval('.route-status', e => e.textContent));
    await page.waitForFunction(() => Array.from(document.querySelectorAll('.leaflet-tile')).some(e => e.complete && e.naturalWidth > 0 && new URL(e.src).searchParams.has('key')), {timeout: 15000});
    console.log('CARTO tiles loaded with the configured key.');
    await screenshot('planner-live-desktop');
    // Deterministic provider responses exercise edits, races and failure states.
    let failRoute = false;
    let slowNext = false;
    const requests = [];
    await page.setRequestInterception(true);
    page.on('request', async request => {
      if (request.url().includes('/route/v1/driving/')) {
        requests.push(request.url());
        const coordinates = request.url().split('/driving/')[1].split('?')[0].split(';').map(p => p.split(',').map(Number));
        const delay = slowNext; slowNext = false;
        if (delay) await new Promise(resolve => setTimeout(resolve, 1700));
        await request.respond({status: 200, contentType: 'application/json', headers: {'access-control-allow-origin': '*'}, body: JSON.stringify(failRoute ? {code: 'NoRoute', routes: []} : {code: 'Ok', routes: [{distance: 543210, duration: 32400, geometry: {type: 'LineString', coordinates}}]})}).catch(() => {});
      } else if (request.url().includes('geocoding-api.open-meteo.com')) {
        await request.respond({status: 200, contentType: 'application/json', headers: {'access-control-allow-origin': '*'}, body: JSON.stringify({results: [{name: 'Chandigarh', admin1: 'Chandigarh', latitude: 30.7333, longitude: 76.7794}]})});
      } else await request.continue().catch(() => {});
    });
    await page.select('[aria-label="Add a stop"]', '3');
    await page.waitForSelector('.planned-road-route');
    await page.waitForFunction(() => document.querySelector('.route-metrics')?.textContent.includes('543 km'));
    await page.select('[aria-label="Add a stop"]', '4');
    await page.waitForFunction(() => document.querySelectorAll('.route-pin').length === 4);
    const stopNames = await page.$$eval('.editable-stop>b', es => es.map(e => e.textContent));
    await page.click(`button[aria-label="Move ${stopNames[1]} earlier"]`);
    assert.deepEqual(await page.$$eval('.editable-stop>b', es => es.map(e => e.textContent)), stopNames.reverse());
    await page.waitForFunction(() => document.querySelector('.route-metrics')?.textContent.includes('543 km'));
    const link = new URL(await page.$eval('.trip-route .route-link', e => e.href));
    assert.equal(link.searchParams.get('waypoints').split('|').length, 2);
    await page.$eval('.origin-field input', e => {const setter = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set; setter.call(e, 'Chandigarh'); e.dispatchEvent(new Event('input', {bubbles: true}));});
    await page.waitForFunction(() => !document.querySelector('.planned-road-route'));
    await click('.origin-actions button', 'Find city');
    await page.waitForSelector('.origin-results button');
    await page.click('.origin-results button');
    await page.waitForSelector('.planned-road-route');
    await click('.planner-form button', 'Save this trip');
    await page.waitForFunction(() => document.querySelector('.toast')?.textContent.includes('Trip saved'));
    const saved = await page.evaluate(async () => (await (await fetch('/api/v1/trips', {headers: {Authorization: 'Bearer ' + localStorage.getItem('wanderer-token')}})).json())[0]);
    assert.deepEqual(saved.stop_ids, [4, 3]);
    assert.equal(saved.origin_point.latitude, 30.7333);
    await page.goto('http://127.0.0.1:5173/profile', {waitUntil: 'networkidle2'});
    await page.waitForSelector('.saved-trips>button');
    await page.click('.saved-trips>button');
    await page.waitForSelector('.planned-road-route');
    assert.equal(await page.$$eval('.editable-stop', es => es.length), 2);
    await screenshot('planner-stops-light-desktop');
    await page.click('[aria-label="Switch to dark mode"]');
    await page.waitForFunction(() => Array.from(document.querySelectorAll('.leaflet-tile')).some(e => e.src.includes('/dark_all/')));
    await screenshot('planner-stops-dark-desktop');
    const modeSelect = '.planner-form>label:last-of-type select';
    await page.select(modeSelect, 'walking');
    await page.waitForFunction(() => !document.querySelector('.planned-road-route'));
    assert((await page.$eval('.route-status', e => e.textContent)).includes('Walking directions'));
    assert.equal(new URL(await page.$eval('.trip-route .route-link', e => e.href)).searchParams.get('travelmode'), 'walking');
    await page.select(modeSelect, 'transit');
    assert.equal(await page.$$eval('.transit-legs a', es => es.length), 3);
    await page.select(modeSelect, 'driving');
    await page.waitForSelector('.planned-road-route');
    failRoute = true;
    await page.select('[aria-label="Add a stop"]', '5');
    await page.waitForSelector('.route-error');
    assert.equal(await page.$$eval('.planned-road-route', es => es.length), 0);
    failRoute = false;
    await click('.route-error button', 'Retry route');
    await page.waitForSelector('.planned-road-route');
    const thirdStop = (await page.$$eval('.editable-stop>b', es => es.map(e => e.textContent)))[2];
    await page.click(`button[aria-label="Remove ${thirdStop} stop"]`);
    slowNext = true;
    await page.select('[aria-label="Add a stop"]', '6');
    await page.waitForFunction(() => document.querySelector('.route-spinner'));
    await page.select(modeSelect, 'walking');
    await new Promise(resolve => setTimeout(resolve, 2000));
    assert.equal(await page.$$eval('.planned-road-route', es => es.length), 0, 'Stale driving route appeared in walking mode');
    await page.select(modeSelect, 'driving');
    await page.waitForSelector('.planned-road-route');
    for (const width of [390, 360]) {
      await page.setViewport({width, height: 844, deviceScaleFactor: 1});
      await noOverflow();
      if (width === 390) await screenshot('planner-stops-dark-mobile');
      await click('.bottom-nav button', 'Profile'); await click('.community-section-links a', 'Settings'); await noOverflow();
      if (width === 390) await screenshot('settings-stitch-dark-mobile');
      await click('.bottom-nav button', 'Trips');
    }
    assert(requests.length >= 5);
    assert.deepEqual(errors, []);
    console.log('PASS: saved themes and navigation, system changes, charcoal palette, mobile layouts, route geometry, ordered stops, origin lookup, save/reopen, dark tiles, walking/transit, provider failure/retry, and stale-request cancellation.');
  } finally {await browser.close();}
})().catch(error => {console.error(error); process.exit(1);});
